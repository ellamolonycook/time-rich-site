import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';
const read=p=>readFileSync(new URL('../../portal/'+p,import.meta.url),'utf8');
let checks=0;
const check=(label,value)=>{assert.ok(value,label);checks++;console.log('  ok   '+label);};
const flush=()=>new Promise(r=>setTimeout(r,0));
function boot(page){
  const dom=new JSDOM(read(page+'.html'),{url:'https://timerich.ai/portal/'+page+'.html',runScripts:'outside-only'});
  const w=dom.window;w.matchMedia=()=>({matches:false,addEventListener(){}});
  w.eval(read('portal-live.js'));
  w.eval(read('portal-design.js'));
  return w;
}
let w=boot('prompts'),d=w.document;
w.eval(read('portal-prompts.js'));
d.dispatchEvent(new w.CustomEvent('trportal:data',{detail:{weeks:[],sessions:[]}}));await flush();
check('current prompt library still renders all cards',d.querySelectorAll('.trp-pcard').length===16);
check('seven-part template preserved',d.querySelector('.trp-ptemplate').textContent.includes('SECOND OPINION')&&d.querySelector('.trp-ptemplate').textContent.includes('BLIND SPOTS'));
const ai=d.querySelector('.trp-ptemplate a[href^="https://claude.ai"]');
check('Open in AI retains the populated prompt',ai&&new URL(ai.href).searchParams.get('q').includes('RED TEAM'));
const search=d.querySelector('.ui-search input');search.value='humanise';search.dispatchEvent(new w.Event('input'));
const matches=Array.from(d.querySelectorAll('.trp-pcard:not([hidden])'));
check('search retains only matching prompts',matches.length>0&&matches.length<16&&matches.every(card=>card.textContent.toLowerCase().includes('humanise')));
check('unrelated template hidden during search',d.querySelector('.trp-ptemplate').hidden);
search.value='zzzz no matching prompt';search.dispatchEvent(new w.Event('input'));
check('empty search announces no results',d.querySelector('.ui-search-status').textContent.includes('No matches'));
search.value='';search.dispatchEvent(new w.Event('input'));
check('clearing search restores all content',d.querySelectorAll('.trp-pcard:not([hidden])').length===16&&!d.querySelector('.trp-ptemplate').hidden);
check('header navigation moved without duplication',d.querySelectorAll('#top-nav > nav').length===1);
const select=d.querySelector('[data-theme-select]');select.addEventListener('change',()=>d.documentElement.dataset.theme=select.value);
d.querySelector('.ui-theme').click();check('day/night switch uses the existing control',select.value==='dark'&&d.querySelector('.ui-theme').getAttribute('aria-checked')==='true');
await flush();w.close();
w=boot('dashboard');d=w.document;
check('dashboard retains setup and learning hooks',d.querySelector('[data-portal-setup]')&&d.querySelector('.ui-learning [data-dash-start]'));
check('progress moved into learning card',d.querySelector('.ui-learning [data-portal-progress]'));
check('video uses original portal asset without autoplay',d.querySelector('.ui-hero video').getAttribute('src')==='assets/accelerator-promo.mp4'&&!d.querySelector('.ui-hero video').autoplay);
check('dashboard has three functioning local shortcuts',d.querySelectorAll('.ui-shortcuts a[href$=".html"]').length===3);
check('only one main page heading remains',d.querySelectorAll('main h1').length===1);
check('mobile menu starts inert',d.querySelector('#mobile-menu').inert===true);
await flush();w.close();
console.log(`\n${checks} portal design checks passed`);
